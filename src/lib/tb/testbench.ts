/**
 * Testbench + run-script generator.
 *
 * Produces a deterministic testbench — VHDL-2008, Verilog-2005 or
 * SystemVerilog-2017, following the session's language — that:
 *  - holds reset across a full falling + rising clock edge (the reference
 *    design loads PC from M[0] on that pair of edges),
 *  - drives IN.PORT from the *fetch PC* so each IN instruction sees the value
 *    the reference model used, regardless of stalls,
 *  - raises the external interrupt when a chosen address is fetched,
 *  - dumps a VCD the Compare step reads.
 */
import { BRAND } from "../site";
import { HDL_INFO, type Hdl } from "../hdl";
import type { ProcessorProfile } from "../isa/profile";
import type { InterruptSpec } from "../sim/simulator";

export interface TestbenchOptions {
  profile: ProcessorProfile;
  memFileName: string;
  inputs: Map<number, number[]>;
  interrupts: InterruptSpec[];
  cycles: number;
  rtlRoot: string;
  /** Compile order found by Code review; falls back to the profile's list. */
  compileOrder?: string[] | null;
  /** Pipeline depth, recorded in the testbench header. */
  stages?: 5 | 6;
  /** Forwarding description, recorded in the testbench header. */
  forwardingNote?: string;
  /** Language of the design and the testbench (default VHDL). */
  hdl?: Hdl;
}

export interface TestbenchBundle {
  files: { name: string; content: string; mode?: "executable" }[];
  notes: string[];
}

/** Allow only identifier-safe names into generated VHDL/shell. */
export function safeIdent(s: string, fallback: string): string {
  return /^[A-Za-z][A-Za-z0-9_]{0,63}$/.test(s) ? s : fallback;
}
export function safeFileName(s: string, fallback: string): string {
  return /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/.test(s) && !s.includes("..") ? s : fallback;
}
export function safeRelPath(s: string, fallback: string): string {
  return /^[A-Za-z0-9._/-]{1,256}$/.test(s) && !s.split("/").includes("..") ? s : fallback;
}

const h = (v: number) => `x"${(v >>> 0).toString(16).toUpperCase().padStart(8, "0")}"`;

export function generateTestbench(o: TestbenchOptions): TestbenchBundle {
  return o.hdl === "verilog" || o.hdl === "systemverilog" ? verilogTestbench(o, o.hdl) : vhdlTestbench(o);
}

function vhdlTestbench(o: TestbenchOptions): TestbenchBundle {
  const hw = o.profile.hardware;
  const notes: string[] = [];
  const ent = safeIdent(hw.entity, "processor");
  const clk = safeIdent(hw.clockPort, "clk");
  const rst = safeIdent(hw.resetPort, "reset");
  const irq = safeIdent(hw.interruptPort, "int");
  const inp = safeIdent(hw.inPort, "in_port");
  const outp = safeIdent(hw.outPort, "out_port");
  const gen = safeIdent(hw.memFileGeneric, "MEM_FILE");
  const pcSig = safeIdent(hw.pcSignal, "pc_out");
  const mem = safeFileName(o.memFileName, "program.mem");
  const cycles = Math.max(10, Math.min(1_000_000, Math.floor(o.cycles)));
  const half = hw.clockPeriodNs / 2;
  const active = hw.resetActive === "low" ? "'0'" : "'1'";
  const inactive = hw.resetActive === "low" ? "'1'" : "'0'";

  const inCases: string[] = [];
  for (const [addr, values] of [...o.inputs.entries()].sort((a, b) => a[0] - b[0])) {
    if (!values.length) continue;
    if (new Set(values).size > 1) {
      notes.push(
        `The IN at 0x${addr.toString(16).toUpperCase()} reads different values on different executions; the testbench drives the first one (${h(values[0])}).`,
      );
    }
    inCases.push(`        when 16#${addr.toString(16).toUpperCase()}# => ${inp}_s <= ${h(values[0])};`);
  }

  const irqLines = o.interrupts.map(
    (i, k) =>
      `      if pc_now = 16#${i.pc.toString(16).toUpperCase()}# and pc_now /= pc_prev then\n` +
      `        seen(${k}) := seen(${k}) + 1;\n` +
      `        if seen(${k}) = ${Math.max(1, Math.min(1_000_000, Math.floor(Number(i.occurrence) || 1)))} then irq_pulse := true; end if;\n` +
      `      end if;`,
  );
  if (o.interrupts.length) {
    notes.push(
      "Interrupt timing in a pipeline differs from the model: the testbench raises the interrupt for one cycle when the address is fetched, so compare interrupt programs with care.",
    );
  }

  const tb = `-- Generated by ${BRAND}. Deterministic; safe to commit.
-- Program: ${mem}   Cycles after reset: ${cycles}   Clock: ${hw.clockPeriodNs} ns   Pipeline: ${o.stages ?? 6} stages${o.forwardingNote ? `, ${o.forwardingNote.replace(/[^A-Za-z0-9 ,/()-]/g, "")}` : ""}
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_${ent} is
  generic (${gen} : string := "${mem}");
end entity;

architecture sim of tb_${ent} is
  signal ${clk}_s   : std_logic := '1';
  signal ${rst}_s   : std_logic := ${active};
  signal ${irq}_s   : std_logic := '0';
  signal ${inp}_s   : std_logic_vector(31 downto 0) := (others => '0');
  signal ${outp}_s  : std_logic_vector(31 downto 0);
  signal pc_mon     : std_logic_vector(31 downto 0);
  signal running    : boolean := true;
begin
  uut : entity work.${ent}
    generic map (${gen} => ${gen})
    port map (
      ${clk} => ${clk}_s, ${rst} => ${rst}_s, ${irq} => ${irq}_s,
      ${inp} => ${inp}_s, ${outp} => ${outp}_s
    );

  ${clk}_s <= not ${clk}_s after ${half} ns when running else '0';

  -- Fetch PC, read through a VHDL-2008 external name.
  pc_mon <= << signal .tb_${ent}.uut.${pcSig} : std_logic_vector(31 downto 0) >>;

  -- IN.PORT follows the fetch PC so every IN sees the value the model used.
  drive_in : process (pc_mon)
  begin
    if is_x(pc_mon) then
      ${inp}_s <= (others => '0');
    else
      case to_integer(unsigned(pc_mon)) is
${inCases.length ? inCases.join("\n") : "        -- (program has no IN instructions)"}
        when others => ${inp}_s <= (others => '0');
      end case;
    end if;
  end process;

  stimulus : process
${o.interrupts.length ? `    type counts is array (0 to ${o.interrupts.length - 1}) of natural;\n    variable seen : counts := (others => 0);\n` : ""}    variable pc_now, pc_prev : integer := -1;
    variable irq_pulse : boolean := false;
  begin
    -- Hold reset over a full falling + rising edge, release mid-cycle.
    ${rst}_s <= ${active};
    wait for ${hw.clockPeriodNs * 2 + half / 5} ns;
    ${rst}_s <= ${inactive};
    for cycle in 1 to ${cycles} loop
      wait until rising_edge(${clk}_s);
      ${irq}_s <= '0';
      if not is_x(pc_mon) then pc_now := to_integer(unsigned(pc_mon)); end if;
${irqLines.join("\n")}
      if irq_pulse then
        ${irq}_s <= '1';
        irq_pulse := false;
      end if;
      pc_prev := pc_now;
    end loop;
    running <= false;
    report "${BRAND}: simulation finished after ${cycles} cycles" severity note;
    wait;
  end process;
end architecture;
`;

  const root = safeRelPath(o.rtlRoot, ".");
  const order = (o.compileOrder?.length ? o.compileOrder : hw.compileOrder).map((f) => safeRelPath(f, "")).filter(Boolean);
  const stopNs = (cycles + 4) * hw.clockPeriodNs;

  const ghdl = `#!/usr/bin/env bash
# Generated by ${BRAND} — run from the folder that holds these files.
# Usage: ./run_ghdl.sh [path/to/rtl]   (default: ${root})
set -euo pipefail
RTL="\${1:-${root}}"
WORK=work
mkdir -p "$WORK"
FLAGS=(--std=08 -fsynopsys --workdir="$WORK")
for f in \\
${order.map((f) => `  "$RTL/${f}" \\`).join("\n")}
; do
  ghdl -a "\${FLAGS[@]}" "$f"
done
ghdl -a "\${FLAGS[@]}" tb_${ent}.vhd
ghdl -e "\${FLAGS[@]}" tb_${ent}
ghdl -r "\${FLAGS[@]}" tb_${ent} --vcd=wave.vcd --stop-time=${stopNs}ns --ieee-asserts=disable-at-0
echo "Wrote wave.vcd — drop it into the Compare step."
`;

  const modelsim = `# Generated by ${BRAND}.
# In ModelSim/Questa: cd to this folder, then  do run_modelsim.do
set RTL "${root}"
vlib work
vmap work work
${order.map((f) => `vcom -2008 -work work $RTL/${f}`).join("\n")}
vcom -2008 -work work tb_${ent}.vhd
vsim -voptargs=+acc work.tb_${ent}
vcd file wave.vcd
vcd add -r /tb_${ent}/*
run ${stopNs} ns
vcd flush
quit -sim
echo "Wrote wave.vcd — drop it into the Compare step."
`;

  const readme = `${BRAND} — hardware run
====================================

Files
  ${mem.padEnd(18)} program image (32-bit binary words)
  tb_${ent}.vhd${" ".repeat(Math.max(1, 14 - ent.length))}testbench (VHDL-2008)
  run_ghdl.sh          GHDL script
  run_modelsim.do      ModelSim / Questa script

GHDL
  chmod +x run_ghdl.sh
  ./run_ghdl.sh path/to/your/src/rtl

ModelSim / Questa
  Edit RTL at the top of run_modelsim.do, then: do run_modelsim.do

Then upload wave.vcd in the Compare step.
${notes.length ? "\nNotes\n" + notes.map((n) => "  - " + n).join("\n") + "\n" : ""}`;

  return {
    files: [
      { name: `tb_${ent}.vhd`, content: tb },
      { name: "run_ghdl.sh", content: ghdl, mode: "executable" },
      { name: "run_modelsim.do", content: modelsim },
      { name: "README.txt", content: readme },
    ],
    notes,
  };
}

/** Interrupt bookkeeping shared by the testbench languages. */
function interruptNotes(o: TestbenchOptions, notes: string[]) {
  if (o.interrupts.length) {
    notes.push(
      "Interrupt timing in a pipeline differs from the model: the testbench raises the interrupt for one cycle when the address is fetched, so compare interrupt programs with care.",
    );
  }
}

const vh = (v: number) => `32'h${(v >>> 0).toString(16).toUpperCase().padStart(8, "0")}`;
/** A delay in ns as a Verilog literal: integers stay integers, others keep 3 decimals. */
const ns = (v: number) => (Number.isInteger(v) ? String(v) : v.toFixed(3).replace(/0+$/, ""));

/**
 * Verilog-2005 or SystemVerilog testbench plus scripts for Icarus Verilog,
 * Verilator and ModelSim/Questa. The fetch PC is read through a hierarchical
 * reference (uut.pc_out), which every Verilog simulator supports.
 */
function verilogTestbench(o: TestbenchOptions, hdl: "verilog" | "systemverilog"): TestbenchBundle {
  const sv = hdl === "systemverilog";
  const info = HDL_INFO[hdl];
  const hw = o.profile.hardware;
  const notes: string[] = [];
  const ent = safeIdent(hw.entity, "processor");
  const clk = safeIdent(hw.clockPort, "clk");
  const rst = safeIdent(hw.resetPort, "reset");
  const irq = safeIdent(hw.verilog?.interruptPort ?? hw.interruptPort, "intr");
  const inp = safeIdent(hw.inPort, "in_port");
  const outp = safeIdent(hw.outPort, "out_port");
  const gen = safeIdent(hw.memFileGeneric, "MEM_FILE");
  const pcSig = safeIdent(hw.pcSignal, "pc_out");
  const mem = safeFileName(o.memFileName, "program.mem");
  const cycles = Math.max(10, Math.min(1_000_000, Math.floor(o.cycles)));
  const half = hw.clockPeriodNs / 2;
  const active = hw.resetActive === "low" ? "1'b0" : "1'b1";
  const inactive = hw.resetActive === "low" ? "1'b1" : "1'b0";
  const reg = sv ? "logic" : "reg  ";
  const net = sv ? "logic" : "wire ";
  const int = sv ? "int    " : "integer";
  const tbName = `tb_${ent}${info.tbExt}`;

  const inCases: string[] = [];
  for (const [addr, values] of [...o.inputs.entries()].sort((a, b) => a[0] - b[0])) {
    if (!values.length) continue;
    if (new Set(values).size > 1) {
      notes.push(
        `The IN at 0x${addr.toString(16).toUpperCase()} reads different values on different executions; the testbench drives the first one (${vh(values[0])}).`,
      );
    }
    inCases.push(`      ${vh(addr)}: ${inp} = ${vh(values[0])};`);
  }
  interruptNotes(o, notes);
  const ints = o.interrupts.map((i, k) => ({
    k,
    pc: i.pc >>> 0,
    occurrence: Math.max(1, Math.min(1_000_000, Math.floor(Number(i.occurrence) || 1))),
  }));

  const tb = `// Generated by ${BRAND}. Deterministic; safe to commit.
// Program: ${mem}   Cycles after reset: ${cycles}   Clock: ${hw.clockPeriodNs} ns   Pipeline: ${o.stages ?? 6} stages${o.forwardingNote ? `, ${o.forwardingNote.replace(/[^A-Za-z0-9 ,/()-]/g, "")}` : ""}
\`timescale 1ns / 1ps

module tb_${ent};
  parameter ${gen} = "${mem}";

  ${reg}        ${clk} = 1'b1;
  ${reg}        ${rst} = ${active};
  ${reg}        ${irq} = 1'b0;
  ${reg} [31:0] ${inp} = 32'h00000000;
  ${net} [31:0] ${outp};
  // Fetch PC, read through a hierarchical reference.
  ${net} [31:0] pc_mon;
  assign pc_mon = uut.${pcSig};

  ${ent} #(.${gen}(${gen})) uut (
    .${clk}(${clk}), .${rst}(${rst}), .${irq}(${irq}),
    .${inp}(${inp}), .${outp}(${outp})
  );

  always #${ns(half)} ${clk} = ~${clk};

  // IN.PORT follows the fetch PC so every IN sees the value the model used.
  always @(pc_mon) begin
    case (pc_mon)
${inCases.length ? inCases.join("\n") : "      // (program has no IN instructions)"}
      default: ${inp} = 32'h00000000;
    endcase
  end

  ${int} cycle;
  ${int} pc_now;
  ${int} pc_prev;
${ints.map((i) => `  ${int} seen${i.k};`).join("\n")}${ints.length ? "\n" : ""}  ${reg}        irq_pulse;

  initial begin
    $dumpfile("wave.vcd");
    $dumpvars(0, tb_${ent});
    pc_now = -1;
    pc_prev = -1;
${ints.map((i) => `    seen${i.k} = 0;`).join("\n")}${ints.length ? "\n" : ""}    irq_pulse = 1'b0;
    // Hold reset over a full falling + rising edge, release mid-cycle.
    ${rst} = ${active};
    #${ns(hw.clockPeriodNs * 2 + half / 5)};
    ${rst} = ${inactive};
    for (cycle = 1; cycle <= ${cycles}; cycle = cycle + 1) begin
      @(posedge ${clk});
      ${irq} <= 1'b0;
      if (^pc_mon !== 1'bx) pc_now = pc_mon;
${ints
  .map(
    (i) =>
      `      if (pc_now == ${vh(i.pc)} && pc_now != pc_prev) begin\n` +
      `        seen${i.k} = seen${i.k} + 1;\n` +
      `        if (seen${i.k} == ${i.occurrence}) irq_pulse = 1'b1;\n` +
      `      end`,
  )
  .join("\n")}${ints.length ? "\n" : ""}      if (irq_pulse) begin
        ${irq} <= 1'b1;
        irq_pulse = 1'b0;
      end
      pc_prev = pc_now;
    end
    $display("${BRAND}: simulation finished after ${cycles} cycles");
    $finish;
  end
endmodule
`;

  const root = safeRelPath(o.rtlRoot, ".");
  const defaults = (hw.verilog?.compileOrder ?? []).map((f) => (sv ? f.replace(/\.v$/, ".sv") : f));
  const order = (o.compileOrder?.length ? o.compileOrder : defaults).map((f) => safeRelPath(f, "")).filter(Boolean);
  const dirs = [...new Set(["", ...order.map((f) => (f.includes("/") ? f.slice(0, f.lastIndexOf("/")) : ""))])];
  const inc = (prefix: string, rtl: string) => dirs.map((d) => `${prefix}${rtl}${d ? "/" + d : ""}`);

  const icarus = `#!/usr/bin/env bash
# Generated by ${BRAND} — run from the folder that holds these files.
# Usage: ./run_icarus.sh [path/to/rtl]   (default: ${root})
set -euo pipefail
RTL="\${1:-${root}}"
FILES=(
${order.map((f) => `  "$RTL/${f}"`).join("\n")}
)
iverilog -g${sv ? "2012" : "2005"} ${inc('-I "', "$RTL").map((x) => x + '"').join(" ")} -s tb_${ent} -o tb_${ent}.vvp "\${FILES[@]}" ${tbName}
vvp -n tb_${ent}.vvp
echo "Wrote wave.vcd — drop it into the Compare step."
`;

  const verilator = `#!/usr/bin/env bash
# Generated by ${BRAND} — needs Verilator 5.0 or later. Run from the folder that holds these files.
# Usage: ./run_verilator.sh [path/to/rtl]   (default: ${root})
set -euo pipefail
RTL="\${1:-${root}}"
FILES=(
${order.map((f) => `  "$RTL/${f}"`).join("\n")}
)
verilator --binary --timing --trace -Wno-fatal -Wno-lint -Wno-style --timescale 1ns/1ps${sv ? "" : " +1364-2005ext+v"} \\
  ${inc('-I"', "$RTL").map((x) => x + '"').join(" ")} \\
  --top-module tb_${ent} -o Vtb_${ent} "\${FILES[@]}" ${tbName}
./obj_dir/Vtb_${ent}
echo "Wrote wave.vcd — drop it into the Compare step."
`;

  const vlog = `vlog${sv ? " -sv" : ""} -work work ${inc("+incdir+", "$RTL").join(" ")}`;
  const modelsim = `# Generated by ${BRAND}.
# In ModelSim/Questa: cd to this folder, then  do run_modelsim.do
set RTL "${root}"
vlib work
vmap work work
${order.map((f) => `${vlog} $RTL/${f}`).join("\n")}
vlog${sv ? " -sv" : ""} -work work ${tbName}
vsim -voptargs=+acc -onfinish stop work.tb_${ent}
run -all
quit -sim
echo "Wrote wave.vcd — drop it into the Compare step."
`;

  const readme = `${BRAND} — hardware run (${info.label})
====================================

Files
  ${mem.padEnd(18)} program image (32-bit binary words)
  ${tbName.padEnd(18)} testbench (${info.label}, ${info.standard}); it writes wave.vcd
  run_icarus.sh        Icarus Verilog script
  run_verilator.sh     Verilator 5 script
  run_modelsim.do      ModelSim / Questa script

Icarus Verilog (free)
  chmod +x run_icarus.sh
  ./run_icarus.sh path/to/your/rtl

Verilator 5 (free)
  chmod +x run_verilator.sh
  ./run_verilator.sh path/to/your/rtl

ModelSim / Questa
  Edit RTL at the top of run_modelsim.do, then: do run_modelsim.do

Vivado simulator (xsim)
  xvlog${sv ? " -sv" : ""} -i path/to/your/rtl <your ${info.extensions.join("/")} files> ${tbName}
  xelab tb_${ent} -s tb
  xsim tb -runall

Then upload wave.vcd in the Compare step.
The testbench expects a module "${ent}" with ports ${clk}, ${rst} (active ${hw.resetActive}), ${irq}, ${inp}, ${outp},
a parameter ${gen} and an internal signal ${pcSig} holding the fetch PC. Edit the names in ${tbName} if yours differ.
${notes.length ? "\nNotes\n" + notes.map((n) => "  - " + n).join("\n") + "\n" : ""}`;

  return {
    files: [
      { name: tbName, content: tb },
      { name: "run_icarus.sh", content: icarus, mode: "executable" },
      { name: "run_verilator.sh", content: verilator, mode: "executable" },
      { name: "run_modelsim.do", content: modelsim },
      { name: "README.txt", content: readme },
    ],
    notes,
  };
}
