import { BRAND } from "../site";
import { HDL_INFO, HDLS, hdlOfPath } from "../hdl";
import type { ReviewReport } from "./review";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

export function reviewToMarkdown(r: ReviewReport, name: string, now = new Date()): string {
  const L: string[] = [];
  L.push(`# Code review: ${esc(name)}`, "");
  L.push(`- Generated by ${BRAND}: ${now.toISOString()}`);
  const langs = HDLS.filter((h) => r.languages[h]).map((h) => `${r.languages[h]} ${HDL_INFO[h].label}`).join(", ");
  const units = [r.entities && `${r.entities} entities`, r.processes && `${r.processes} processes`, r.modules && `${r.modules} modules`, r.alwaysBlocks && `${r.alwaysBlocks} always blocks`].filter(Boolean).join(", ");
  L.push(`- ${r.files} source files (${langs || "none"}), ${r.lines.toLocaleString("en-US")} lines, ${units ? units + ", " : ""}${r.instances} instances`);
  L.push(`- Top level: ${r.top ?? "not found"}${r.testbenches.length ? `; testbenches: ${r.testbenches.join(", ")}` : ""}`);
  L.push(
    `- Pipeline: ${r.pipeline.selected} stages selected; ${r.pipeline.inferred ? `code looks like ${r.pipeline.inferred} stages` : "depth not recognised"} (${r.pipeline.registersFound.map((p) => p.pair).join(", ") || "no pipeline registers found"})`,
  );
  L.push(`- Findings: ${r.counts.error} errors, ${r.counts.warning} warnings, ${r.counts.info} notes`, "");
  for (const sev of ["error", "warning", "info"] as const) {
    const list = r.findings.filter((f) => f.severity === sev);
    if (!list.length) continue;
    L.push(`## ${sev === "error" ? "Errors" : sev === "warning" ? "Warnings" : "Notes"}`, "");
    for (const f of list) {
      L.push(`### ${esc(f.title)}`, "");
      L.push(`\`${f.file}:${f.line}\` · ${f.category}`, "");
      L.push(f.message, "");
      L.push(`**Fix:** ${f.fix}`, "");
      if (f.fixCode) L.push("```" + (hdlOfPath(f.file) ?? "vhdl"), f.fixCode, "```", "");
    }
  }
  L.push("## Compile order", "");
  if (r.compileOrderNote) L.push(`> ${r.compileOrderNote}`, "");
  r.compileOrder.forEach((p, i) => L.push(`${i + 1}. ${p}`));
  L.push("");
  return L.join("\n");
}
